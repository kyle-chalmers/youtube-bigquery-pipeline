            "CASE WHEN r.d IS NULL THEN 'analytics_only' WHEN a.d IS NULL THEN 'reporting_only' END AS one_sided "
            "FROM r FULL OUTER JOIN a USING (d), win WHERE COALESCE(r.d, a.d) BETWEEN win.lo AND win.hi ORDER BY activity_date;",
