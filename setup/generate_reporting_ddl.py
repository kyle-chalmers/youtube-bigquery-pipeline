            "ABS(IFNULL(reporting_subscribers, 0) - IFNULL(analytics_subscribers, 0)) AS absolute_diff "
            "FROM r FULL OUTER JOIN a USING (d, video_id) WHERE ABS(IFNULL(reporting_subscribers, 0) - IFNULL(analytics_subscribers, 0)) > 1 "
