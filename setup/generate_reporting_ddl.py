            "reconcile_views_video_day",
            "Every joined video-day across the shared window. Grain: activity date and video id. Threshold: greater of 5 views or 5 percent of Analytics views.",
            f"WITH rd AS (SELECT DISTINCT report_date AS d FROM {traffic}), ad AS (SELECT DISTINCT activity_date AS d FROM {analytics_traffic}), "
