            f"r AS (SELECT report_date AS d, video_id, SUM(subscribers_gained) AS reporting_subscribers FROM {basic} "
            "WHERE video_id IS NOT NULL AND report_date IN (SELECT d FROM shared) GROUP BY d, video_id), "
